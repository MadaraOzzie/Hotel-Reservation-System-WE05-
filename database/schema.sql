CREATE TABLE IF NOT EXISTS guests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE, phone VARCHAR(30) NOT NULL,
 type VARCHAR(20) NOT NULL CHECK(type IN ('STANDARD','VIP')),
 discount_rate DECIMAL(5,4) NOT NULL CHECK(discount_rate BETWEEN 0 AND 0.5)
);
CREATE TABLE IF NOT EXISTS rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 number VARCHAR(12) NOT NULL UNIQUE, type VARCHAR(20) NOT NULL CHECK(type IN ('STANDARD','SUITE')),
 capacity INT NOT NULL CHECK(capacity BETWEEN 1 AND 12), base_price DECIMAL(12,2) NOT NULL CHECK(base_price>0),
 luxury_tax DECIMAL(5,4) NOT NULL CHECK(luxury_tax BETWEEN 0 AND 0.3),
 status VARCHAR(20) NOT NULL CHECK(status IN ('AVAILABLE','MAINTENANCE'))
);
CREATE TABLE IF NOT EXISTS staff (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE, phone VARCHAR(30) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK(role IN ('MANAGER','RECEPTIONIST')),
 shift VARCHAR(20) NOT NULL CHECK(shift IN ('MORNING','EVENING','NIGHT')), password_hash VARCHAR(256) NOT NULL
);
CREATE TABLE IF NOT EXISTS services (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE, category VARCHAR(20) NOT NULL CHECK(category IN ('DINING','WELLNESS','TRANSPORT','LEISURE')),
 type VARCHAR(20) NOT NULL CHECK(type IN ('PAID','COMPLIMENTARY')), base_cost DECIMAL(12,2) NOT NULL CHECK(base_cost>=0),
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','UNAVAILABLE')), description VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 guest_id BIGINT NOT NULL REFERENCES guests(id), room_id BIGINT NOT NULL REFERENCES rooms(id),
 check_in DATE NOT NULL, check_out DATE NOT NULL, party_size INT NOT NULL CHECK(party_size BETWEEN 1 AND 12),
 type VARCHAR(20) NOT NULL CHECK(type IN ('ADVANCE','WALK_IN')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('CONFIRMED','CHECKED_IN','CHECKED_OUT','CANCELLED')),
 total DECIMAL(14,2) NOT NULL CHECK(total>=0), cancellation_fee DECIMAL(14,2) NOT NULL CHECK(cancellation_fee>=0),
 CHECK(check_out>check_in)
);
CREATE INDEX IF NOT EXISTS reservation_availability ON reservations(room_id,check_in,check_out,status);
CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_id BIGINT REFERENCES reservations(id), author VARCHAR(100) NOT NULL,
 type VARCHAR(20) NOT NULL CHECK(type IN ('VERIFIED','ANONYMOUS')), rating INT NOT NULL CHECK(rating BETWEEN 1 AND 5),
 text VARCHAR(2000) NOT NULL, status VARCHAR(20) NOT NULL CHECK(status IN ('PUBLISHED','HIDDEN')),
 CHECK((type='VERIFIED' AND reservation_id IS NOT NULL) OR (type='ANONYMOUS' AND reservation_id IS NULL))
);
