-- Category 2: Room Management
-- H2 SQL. Referenced parent tables must exist first; full schema is in the complete project.

CREATE TABLE IF NOT EXISTS rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 number VARCHAR(12) NOT NULL UNIQUE, type VARCHAR(20) NOT NULL CHECK(type IN ('STANDARD','SUITE')),
 capacity INT NOT NULL CHECK(capacity BETWEEN 1 AND 12), base_price DECIMAL(12,2) NOT NULL CHECK(base_price>0),
 luxury_tax DECIMAL(5,4) NOT NULL CHECK(luxury_tax BETWEEN 0 AND 0.3),
 status VARCHAR(20) NOT NULL CHECK(status IN ('AVAILABLE','MAINTENANCE'))
);
